import 'dart:convert';

import 'app_templates.dart';
import 'openrouter_service.dart';

/// A complete project ready to be pushed to GitHub.
class GeneratedProject {
  GeneratedProject({
    required this.appName,
    required this.slug,
    required this.label,
    required this.description,
    required this.files,
  });

  final String appName;
  final String slug;
  final String label;
  final String description;
  /// path -> content (rendered, ready to push)
  final Map<String, String> files;

  String get appId => 'com.liberto.$slug';
}

class CodeGenError implements Exception {
  CodeGenError(this.message);
  final String message;
  @override
  String toString() => message;
}

/// Calls the AI model and turns its answer into a full buildable project.
class CodeGenerator {
  static Map<String, String> _vars({
    required String slug,
    required String label,
    required String description,
  }) {
    final appId = 'com.liberto.$slug';
    return {
      'APP_ID': appId,
      'APP_ID_US': appId.replaceAll('.', '_'),
      'PKG_PATH': appId.replaceAll('.', '/'),
      'APP_NAME_SNAKE': slug,
      'LABEL': label.length > 30 ? label.substring(0, 30) : label,
      'DESCRIPTION': description.length > 120
          ? description.substring(0, 120)
          : description,
    };
  }

  static String _slug(String desc) {
    final words =
        RegExp(r'[a-zA-Z0-9]+').allMatches(desc).take(3).map((m) => m.group(0)!).toList();
    var s = words.join('_').toLowerCase();
    if (s.length < 3) s = 'my_app';
    if (s.length > 24) s = s.substring(0, 24);
    return s.replaceAll(RegExp(r'[^a-z0-9_]'), '');
  }

  /// Extracts a JSON object from a possibly-noisy model answer.
  static Map<String, dynamic> _extractJson(String raw) {
    var text = raw.trim();
    final fence = RegExp(r'```(?:json)?\s*(\{[\s\S]*?\})\s*```').firstMatch(text);
    if (fence != null) text = fence.group(1)!;
    final first = text.indexOf('{');
    final last = text.lastIndexOf('}');
    if (first >= 0 && last > first) text = text.substring(first, last + 1);
    return jsonDecode(text) as Map<String, dynamic>;
  }

  static Future<GeneratedProject> generate({
    required String apiKey,
    required String model,
    required StackTemplate template,
    required String description,
  }) async {
    final slug = _slug(description);
    final label = description.length > 24 ? description.substring(0, 24) : description;
    final vars = _vars(slug: slug, label: label, description: description);

    final allPaths = <String>[
      renderTemplate(template.mainAiPath, vars),
      for (final p in template.extraAiPaths) renderTemplate(p, vars),
    ];

    final prompt = renderTemplate(
      '${template.aiInstructions}\n\n'
      'USER REQUEST (build this app EXACTLY as described):\n'
      '"""$description"""\n\n'
      'Remember: JSON only. Paths exactly as listed under REQUIRED PATHS.',
      vars,
    );

    final svc = OpenRouterService();
    final full = await svc.streamChat(
      apiKey: apiKey,
      model: model,
      messages: const [],
      systemPrompt: prompt,
      onToken: (_) {},
      connectTimeoutSeconds: 120,
    );

    final GeneratedProject fallback() => _fallbackProject(template, vars, full);

    Map<String, dynamic>? json;
    try {
      json = _extractJson(full);
    } catch (_) {
      return fallback();
    }

    final filesRaw = json?['files'] as List?;
    if (filesRaw == null || filesRaw.isEmpty) return fallback();

    final byPath = <String, String>{};
    for (final f in filesRaw) {
      final m = f as Map<String, dynamic>;
      final p = (m['path'] as String?) ?? '';
      final c = (m['content'] as String?) ?? '';
      if (p.isNotEmpty && c.isNotEmpty) byPath[p] = c;
    }

    // Match AI files to expected paths (exact match first).
    final mainContent = byPath[allPaths[0]];
    if (mainContent == null) return fallback();

    final files = <String, String>{
      for (final e in template.files.entries) e.key: renderTemplate(e.value, vars),
      allPaths[0]: mainContent,
      for (var i = 1; i < allPaths.length; i++)
        allPaths[i]: (byPath[allPaths[i]] ?? _emptyExtra()),
    };

    final appName = (json!['app_name'] as String?) ?? 'Liberto App';
    final outLabel = (json['label'] as String?) ?? label;
    final outDesc = (json['description'] as String?) ??
        'Android app generated by Liberto';

    return GeneratedProject(
      appName: appName,
      slug: slug,
      label: outLabel,
      description: outDesc,
      files: files,
    );
  }

  static String _emptyExtra() => '// generated by Liberto';

  /// When the model ignored the JSON contract, still produce a buildable
  /// project: use the raw answer as the main file if it looks like code,
  /// otherwise use a minimal working skeleton.
  static GeneratedProject _fallbackProject(
      StackTemplate template, Map<String, String> vars, String raw) {
    var main = raw.trim();
    // strip fences
    main = main.replaceAll(RegExp(r'^```[a-z]*\s*\n', multiLine: true), '');
    main = main.replaceAll(RegExp(r'\n```\s*$', multiLine: true), '');

    final looksLikeCode = main.contains('package ') ||
        main.contains('import ') ||
        main.contains('#include') ||
        main.contains('void main');
    final mainPath = renderTemplate(template.mainAiPath, vars);
    final content = looksLikeCode ? main : _skeleton(template.id, vars);

    return GeneratedProject(
      appName: 'Liberto App',
      slug: vars['APP_ID']!.split('.').last,
      label: vars['LABEL']!,
      description: 'Android app generated by Liberto',
      files: {
        for (final e in template.files.entries)
          e.key: renderTemplate(e.value, vars),
        mainPath: content,
        for (final p in template.extraAiPaths)
          renderTemplate(p, vars): _emptyExtra(),
      },
    );
  }

  static String _skeleton(String stackId, Map<String, String> v) {
    final pkg = v['APP_ID']!;
    final label = v['LABEL']!;
    switch (stackId) {
      case 'flutter':
        return '''import 'package:flutter/material.dart';

void main() => runApp(const LibertoApp());

class LibertoApp extends StatelessWidget {
  const LibertoApp({super.key});
  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: "$label",
      debugShowCheckedModeBanner: false,
      theme: ThemeData(useMaterial3: true),
      home: Scaffold(
        appBar: AppBar(title: const Text("$label")),
        body: const Center(child: Text("سلام! این اپ با Liberto ساخته شد")),
      ),
    );
  }
}
''';
      case 'java':
        return '''package $pkg;

import android.os.Bundle;
import android.widget.LinearLayout;
import android.widget.TextView;
import androidx.appcompat.app.AppCompatActivity;

public class MainActivity extends AppCompatActivity {
    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        TextView text = new TextView(this);
        text.setText("$label");
        text.setTextSize(24);
        LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.addView(text);
        setContentView(root);
    }
}
''';
      case 'cpp':
        return '''#include <jni.h>
#include <string>

extern "C" std::string liberto_core(const std::string& input) {
    return std::string("Hello from C++: ") + input;
}

extern "C" {
jstring nativeLogicImpl(JNIEnv* env, jclass, jstring input) {
    const char* in = env->GetStringUTFChars(input, nullptr);
    std::string out = liberto_core(in);
    env->ReleaseStringUTFChars(input, in);
    return env->NewStringUTF(out.c_str());
}
}
static JNINativeMethod methods[] = {
    {"nativeLogic", "(Ljava/lang/String;)Ljava/lang/String;", (void*)nativeLogicImpl},
};
extern "C" JNIEXPORT jint JNI_OnLoad(JavaVM* vm, void*) {
    JNIEnv* env = nullptr;
    if (vm->GetEnv((void**)&env, JNI_VERSION_1_6) != JNI_OK) return JNI_ERR;
    jclass clazz = env->FindClass("${v['APP_ID_US']}/MainActivity");
    if (clazz && env->RegisterNatives(clazz, methods, 1) != JNI_OK) return JNI_ERR;
    return JNI_VERSION_1_6;
}
''';
      default:
        return '''package $pkg

import android.os.Bundle
import android.widget.LinearLayout
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity

class MainActivity : AppCompatActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val text = TextView(this).apply {
            text = "$label"
            textSize = 24f
        }
        val root = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            addView(text)
        }
        setContentView(root)
    }
}
''';
    }
  }
}
